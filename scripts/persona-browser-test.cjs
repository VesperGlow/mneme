// Run against the disposable console_fixture; requires existing playwright-core/Chromium.
const { chromium } = require('playwright-core');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const BASE = 'http://127.0.0.1:18080';
(async () => {
  fs.mkdirSync('artifacts', { recursive: true });
  const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, reducedMotion: 'reduce' });
    const page = await context.newPage(); const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(`${BASE}/console/#agent`);
    await page.locator('#password').fill('console-fixture-password');
    await page.getByRole('button', { name: '解锁控制台' }).click();
    const panel = page.locator('#persona-derivation');
    await panel.locator(':scope > summary').click();
    await page.locator('#derivation-status').waitFor();
    assert.match(await page.locator('#derivation-status').innerText(), /尚未生成/);
    await page.getByRole('button', { name: '生成行为画像', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#derivation-status')?.textContent === '已生效');
    assert.equal(await page.locator('[data-dimension]').count(), 6);
    const overall = page.locator('[data-dimension="overall"]');
    await overall.locator('summary').click();
    await page.locator('[name="description-overall"]').fill('人工保留的沉静表达 <img src=x onerror="window.__persona_xss=1">');
    await page.locator('[name="lock-overall"]').check();
    await page.getByRole('button', { name: '核对并保存画像' }).click();
    await page.waitForFunction(() => document.querySelector('[data-dimension="overall"] summary').textContent.includes('人工编辑'));
    await page.getByRole('button', { name: '重新生成', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#generate-derivation')?.disabled === false && document.querySelector('#derivation-status')?.textContent === '已生效');
    await overall.locator('summary').click();
    assert.match(await page.locator('[name="description-overall"]').inputValue(), /人工保留/);
    assert.equal(await page.locator('[name="lock-overall"]').isChecked(), true);
    assert.equal(await page.evaluate(() => window.__persona_xss), undefined);
    // Unsaved derivative edits survive saving a changed raw persona.
    await page.locator('[name="description-overall"]').fill('尚未保存的本地画像草稿');
    const raw = page.locator('[data-setting="persona"]'); await raw.locator(':scope > summary').click();
    await page.locator('#persona-style').fill('自然，安静直接，尊重自主；新的原始设定。');
    await page.getByRole('button', { name: '保存性格', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#derivation-status')?.textContent.includes('待更新'));
    await overall.locator('summary').click();
    assert.equal(await page.locator('[name="description-overall"]').inputValue(), '尚未保存的本地画像草稿');
    await page.getByRole('button', { name: '核对并保存画像' }).click();
    await page.waitForFunction(() => document.querySelector('#derivation-status')?.textContent === '已生效');
    await page.locator('.derivation-effective > summary').click();
    assert.match(await page.locator('.derivation-effective pre').innerText(), /尚未保存的本地画像草稿/);
    assert.match(await page.locator('.derivation-effective pre').innerText(), /原始人格为准/);
    await page.locator('#persona-preview [name="message"]').fill('今天好困。');
    await page.getByRole('button', { name: '预览回复', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#preview-answer')?.textContent && !document.querySelector('#preview-answer').textContent.includes('正在生成'));
    const ledger = await context.request.get(`${BASE}/v1/messages`);
    const history = await ledger.json();
    assert.equal(history.messages.length, 0, 'preview does not save chat messages');
    await page.locator('#derivation-form [name="enabled"]').uncheck();
    await page.getByRole('button', { name: '核对并保存画像' }).click();
    await page.waitForFunction(() => document.querySelector('#derivation-status')?.textContent.includes('已停用'));
    await page.locator('.derivation-history > summary').click();
    await page.locator('.derivation-history details > summary').first().click();
    await page.locator('[data-rollback]').first().click();
    await page.waitForFunction(() => document.querySelector('#derivation-status')?.textContent === '已生效');
    await page.screenshot({ path: 'artifacts/persona-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.waitForFunction(() => document.documentElement.scrollWidth <= window.innerWidth);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    await page.screenshot({ path: 'artifacts/persona-mobile.png', fullPage: true, animations: 'disabled' });
    assert.deepEqual(errors, []);
    console.log('Persona WebUI: generation, edit/lock, raw invalidation, draft preservation, effective prompt, isolated preview, disable, rollback, XSS and mobile checks passed.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });

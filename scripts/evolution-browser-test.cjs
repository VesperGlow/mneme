// Disposable console_fixture only; requires the already-installed playwright-core and Chromium.
const { chromium } = require('playwright-core');
const assert = require('node:assert/strict');
const BASE = 'http://127.0.0.1:18080';
(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, reducedMotion: 'reduce' });
    const page = await context.newPage(); const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${BASE}/console/#agent`);
    await page.locator('#password').fill('console-fixture-password');
    await page.getByRole('button', { name: '解锁控制台' }).click();
    await page.locator('#persona-derivation').waitFor();
    const response = await context.request.post(`${BASE}/v1/chat`, { data: { request_id: require('node:crypto').randomUUID(), message: '以后聊天请不要每次追问，安静一点。<img src=x onerror="window.__evolution_xss=1">' } });
    assert.equal(response.status(), 200); await response.text();
    await page.reload();
    const panel = page.locator('#persona-derivation');
    if (!await panel.evaluate(el => el.open)) await panel.locator(':scope > summary').click();
    const host = page.locator('.evolution-host'); await page.locator('#evolution-status').waitFor();
    assert.match(await page.locator('#evolution-status').innerText(), /尚无/);
    await host.locator('.evolution-reflection > summary').click();
    await host.locator('[name="source"]').first().check();
    await page.getByRole('button', { name: '反思并验证', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#evolution-status')?.textContent.includes('已生效'));
    assert.equal(await host.locator('.evolution-note').count(), 1);
    assert.equal(await page.evaluate(() => window.__evolution_xss), undefined);
    await host.locator('[name="locked"]').check();
    await host.locator('[name="paused"]').check();
    await page.getByRole('button', { name: '保存进化设置', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.evolution-history')?.textContent.includes('用户调整'));
    assert.equal(await host.locator('[name="locked"]').isChecked(), true);
    assert.equal(await host.locator('[name="paused"]').isChecked(), true);
    assert.equal(await host.locator('#evolution-reflect button').isDisabled(), true);
    await panel.locator('.derivation-effective > summary').click();
    assert.match(await panel.locator('.derivation-effective pre').innerText(), /evolution_memory/);
    await host.locator('.evolution-history > summary').click();
    await host.locator('[data-evolution-revision="1"] > summary').click();
    assert.match(await host.locator('[data-evolution-revision="1"]').innerText(), /真实用户反馈/);
    await host.locator('[data-evolution-revision="1"] > details > summary').last().click();
    assert.match(await host.locator('[data-evolution-revision="1"]').innerText(), /independent_batched_rehearsal_v1/);
    await page.getByRole('button', { name: '清空进化层并记录回退', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#evolution-status')?.textContent.includes('尚无'));
    await host.locator('.evolution-history > summary').click();
    await host.locator('[data-evolution-revision="1"] > summary').click();
    await host.locator('[data-evolution-rollback="1"]').click();
    await page.waitForFunction(() => document.querySelector('#evolution-status')?.textContent.includes('已生效'));
    const stateResponse = await context.request.get(`${BASE}/v1/console/persona/evolution`);
    const state = await stateResponse.json();
    assert.equal(state.state.version, 4); assert.equal(state.history.length, 4);
    await page.screenshot({ path: 'artifacts/evolution-desktop.png', fullPage: true, animations: 'disabled' });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.waitForFunction(() => document.documentElement.scrollWidth <= window.innerWidth);
    await page.screenshot({ path: 'artifacts/evolution-mobile.png', fullPage: true, animations: 'disabled' });
    assert.deepEqual(errors, []);
    console.log('Evolution WebUI: real feedback, reflection/validation, runtime prompt, evidence/diffs, locks/pause, version rollback, XSS and mobile checks passed.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });

// Test-only dependency: playwright-core, using the host's existing Chromium.
// Run against `cargo run --example console_fixture`; no production credentials are used.
const { chromium } = require('playwright-core');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const BASE = 'http://127.0.0.1:18080';
const TOKEN = 'console-test-token-01234567890123456789';
const output = path.resolve('artifacts');
fs.mkdirSync(output, { recursive: true });

(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  const errors = [];
  let created;
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce', locale: 'zh-CN' });
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if (message.type() === 'error' && !message.text().includes('401')) errors.push(message.text()); });
    await page.goto(`${BASE}/console/`);
    await page.getByRole('heading', { name: '进入你的记忆空间' }).waitFor();
    await page.screenshot({ path: path.join(output, 'console-login.png'), fullPage: true });
    await page.locator('#token').fill(TOKEN);
    await page.getByRole('button', { name: '解锁控制台' }).click();
    await page.getByRole('heading', { name: '最近留下的片段' }).waitFor();
    await page.screenshot({ path: path.join(output, 'console-desktop.png'), fullPage: true });
    assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0);
    await page.getByRole('link', { name: '记忆库', exact: true }).click();
    await page.getByRole('button', { name: '新增记忆', exact: true }).click();
    const marker = `Console QA ${Date.now()}`;
    const unsafe = `${marker} 字面文本 <img src=x onerror="window.__xss=1">`;
    await page.locator('#memory-content').fill(unsafe);
    await page.locator('#editor select[name=kind]').selectOption('preference');
    await page.locator('#editor input[name=entities]').fill('浏览器测试，Console');
    const post = page.waitForResponse(response => new URL(response.url()).pathname === '/v1/memories' && response.request().method() === 'POST');
    await page.getByRole('button', { name: '创建记忆', exact: true }).click();
    const body = await (await post).json(); created = body.memory.id;
    await page.locator('#editor').waitFor({ state: 'hidden' });
    await page.locator('#memory-search').fill(marker);
    await page.getByRole('button', { name: unsafe, exact: true }).waitFor();
    await page.getByRole('button', { name: unsafe, exact: true }).click();
    await page.locator('#detail .detail-content').waitFor();
    assert.equal(await page.locator('#detail img').count(), 0);
    assert.equal(await page.evaluate(() => window.__xss), undefined);
    await page.locator('#detail').getByRole('button', { name: '编辑记忆', exact: true }).click();
    const edited = `${marker} 已更新的记忆内容`;
    await page.locator('#memory-content').fill(edited);
    await page.getByRole('button', { name: '保存修改', exact: true }).click();
    await page.locator('#editor').waitFor({ state: 'hidden' });
    await page.locator('#detail .detail-content', { hasText: edited }).waitFor();
    await page.locator('#detail .version').nth(1).locator('summary').click();
    assert((await page.locator('#detail').innerText()).includes(unsafe));
    assert((await page.locator('#detail').innerText()).includes('修订 2'));
    await page.screenshot({ path: path.join(output, 'console-detail.png'), fullPage: true });
    await page.locator('#detail').getByRole('button', { name: '删除', exact: true }).click();
    await page.getByRole('button', { name: '确认删除', exact: true }).click();
    await page.locator('#confirm').waitFor({ state: 'hidden' });
    await page.getByRole('heading', { name: '没有找到匹配的记忆' }).waitFor();
    const deleted = await context.request.get(`${BASE}/v1/memories/${created}`, { headers: { Authorization: `Bearer ${TOKEN}` } });
    assert((await deleted.json()).memory.deleted_at);
    await page.getByRole('link', { name: '检索实验室', exact: true }).click();
    await page.locator('#retrieval-query').fill('我现在住在哪座城市？');
    await page.getByRole('button', { name: '运行检索', exact: true }).click();
    await page.getByRole('heading', { name: 'Reranker 与最终排序' }).waitFor();
    assert((await page.locator('#retrieval-results').innerText()).includes('向量召回'));
    assert((await page.locator('#retrieval-results').innerText()).includes('0.8700'));
    assert(!(await page.locator('#retrieval-results').innerText()).includes(marker));
    await page.screenshot({ path: path.join(output, 'console-retrieval.png'), fullPage: true });
    await page.getByRole('link', { name: '系统状态', exact: true }).click();
    await page.getByRole('heading', { name: '后台处理队列' }).waitFor();
    await page.screenshot({ path: path.join(output, 'console-system.png'), fullPage: true });
    await page.getByRole('button', { name: '退出登录', exact: true }).click();
    await page.getByRole('heading', { name: '进入你的记忆空间' }).waitFor();
    assert(!(await page.locator('body').innerText()).includes('用户目前住在成都'));
    assert.equal(await page.locator('dialog[open]').count(), 0);
    await page.locator('#token').fill(TOKEN);
    await page.getByRole('button', { name: '解锁控制台' }).click();
    await page.locator('#page').waitFor();
    await page.reload();
    await page.getByRole('heading', { name: '进入你的记忆空间' }).waitFor();
    await page.locator('#token').fill(TOKEN);
    await page.getByRole('button', { name: '解锁控制台' }).click();
    await page.locator('#page').waitFor();
    await page.evaluate(() => { const clock = Date.now.bind(Date); Date.now = () => clock() + 31 * 60 * 1000; });
    await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')));
    await page.getByRole('heading', { name: '进入你的记忆空间' }).waitFor();
    const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1, locale: 'zh-CN', reducedMotion: 'reduce' });
    const mobile = await mobileContext.newPage();
    mobile.on('pageerror', error => errors.push(error.message));
    await mobile.goto(`${BASE}/console/`);
    await mobile.locator('#token').fill(TOKEN);
    await mobile.getByRole('button', { name: '解锁控制台' }).click();
    await mobile.getByRole('heading', { name: '最近留下的片段' }).waitFor();
    await mobile.screenshot({ path: path.join(output, 'console-mobile.png'), fullPage: true });
    assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile overview overflows');
    await mobile.getByRole('link', { name: '记忆库', exact: true }).click();
    await mobile.locator('.library-table').waitFor();
    await mobile.screenshot({ path: path.join(output, 'console-mobile-library.png'), fullPage: true });
    assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile library overflows');
    await mobile.locator('.memory-title').first().click();
    await mobile.locator('#detail .detail-content').waitFor();
    assert((await mobile.locator('#detail').boundingBox()).width <= 390);
    await mobileContext.close(); await context.close();
    assert.deepEqual(errors, [], `Browser errors: ${errors.join('\n')}`);
    console.log('PASS: desktop/mobile UI, login/logout/reload, live CRUD, revisions, XSS escaping, retrieval scores and system status.');
  } finally {
    if (created) await fetch(`${BASE}/v1/memories/${created}`, { method: 'DELETE', headers: { Authorization: `Bearer ${TOKEN}` } }).catch(() => {});
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
